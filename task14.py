a = 10
b = 5
c = 2

# Operator Precedence
result1 = a + b * c
result2 = (a + b) * c

print("Operator Precedence:")
print("10 + 5 * 2 =", result1)
print("(10 + 5) * 2 =", result2)

# Operator Associativity
result3 = 10 - 5 - 2
result4 = 10 ** 2 ** 3

print("\nOperator Associativity:")
print("10 - 5 - 2 =", result3)
print("10 ** 2 ** 3 =", result4)
